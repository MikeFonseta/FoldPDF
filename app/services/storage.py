"""File handling on disk: directory layout, internal names, permissions and removal.

Internal file names are always generated by the service (UUIDs) and never
depend on the name provided by the client.
"""

from __future__ import annotations

import logging
import os
import re
import shutil
import stat
import time
import uuid
from pathlib import Path
from typing import BinaryIO

from fastapi import UploadFile

from app.config import Settings
from app.exceptions import EmptyUploadError, UploadTooLargeError

logger = logging.getLogger(__name__)

CHUNK_SIZE = 1024 * 1024
PART_SUFFIX = ".part"
_UUID = r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}"
UUID_RE = re.compile(rf"^{_UUID}$")
MANAGED_FILE_RE = re.compile(rf"^({_UUID})(\.docx|\.xlsx|\.pptx|\.pdf|\.pdf\.tmp|\.part)$")

_IS_POSIX = os.name == "posix"


def is_uuid(value: str) -> bool:
    return bool(UUID_RE.match(value))


def make_private(path: Path) -> None:
    """Restrict permissions to the owner (POSIX). On Windows the inherited ACLs apply."""
    if not _IS_POSIX:
        return
    try:
        os.chmod(path, 0o700 if path.is_dir() else 0o600)
    except OSError as exc:
        logger.warning("Cannot set permissions on %s: %s", path, exc)


def create_private_file(path: Path) -> BinaryIO:
    """Create a new file (fails if it exists) readable only by the owner."""
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0)
    fd = os.open(path, flags, 0o600)
    return os.fdopen(fd, "wb")


def remove_file(path: Path, attempts: int = 5, delay: float = 0.2) -> bool:
    """Remove a file, tolerating the temporary locks typical of Windows."""
    for attempt in range(attempts):
        try:
            path.unlink(missing_ok=True)
            return True
        except PermissionError:
            if attempt == attempts - 1:
                logger.warning("File is locked, removal postponed: %s", path)
                return False
            time.sleep(delay * (attempt + 1))
        except OSError as exc:
            logger.warning("Cannot remove %s: %s", path, exc)
            return False
    return False


def _retry_readonly(func, path, exc):  # type: ignore[no-untyped-def]
    # On Windows read-only files cannot be removed: clear the flag and retry.
    if isinstance(exc, PermissionError):
        os.chmod(path, stat.S_IWRITE)
        func(path)
    else:
        raise exc


def remove_tree(path: Path, attempts: int = 5, delay: float = 0.3) -> bool:
    """Recursively remove a directory, retrying a few times if files are locked."""
    for attempt in range(attempts):
        if not path.exists():
            return True
        try:
            shutil.rmtree(path, onexc=_retry_readonly)
            return True
        except FileNotFoundError:
            return True
        except OSError as exc:
            if attempt == attempts - 1:
                logger.warning("Cannot remove directory %s: %s", path, exc)
                return False
            time.sleep(delay * (attempt + 1))
    return False


def safe_child(base: Path, name: str) -> Path:
    """Return `base/name`, guaranteeing it does not escape `base` (path traversal protection)."""
    candidate = (base / name).resolve()
    if candidate.parent != base.resolve():
        raise ValueError("Invalid internal file name")
    return candidate


class Storage:
    def __init__(self, settings: Settings) -> None:
        self.upload_dir = settings.upload_dir
        self.result_dir = settings.result_dir
        self.profile_dir = settings.profile_dir
        self.work_dir = settings.work_dir
        self.database_dir = settings.database_path.parent

    @property
    def all_dirs(self) -> list[Path]:
        return [self.upload_dir, self.result_dir, self.profile_dir, self.work_dir, self.database_dir]

    def ensure_dirs(self) -> None:
        for directory in self.all_dirs:
            directory.mkdir(parents=True, exist_ok=True)
            make_private(directory)

    def check_writable(self) -> bool:
        for directory in self.all_dirs:
            probe = directory / f".probe-{uuid.uuid4()}"
            try:
                with create_private_file(probe) as fh:
                    fh.write(b"ok")
                probe.unlink()
            except OSError:
                return False
        return True

    def input_path(self, name: str) -> Path:
        return safe_child(self.upload_dir, name)

    def result_path(self, name: str) -> Path:
        return safe_child(self.result_dir, name)

    async def receive_upload(self, upload: UploadFile, max_bytes: int) -> tuple[Path, int]:
        """Save the upload in chunks to a temporary file, enforcing the size limit."""
        tmp = self.upload_dir / f"{uuid.uuid4()}{PART_SUFFIX}"
        total = 0
        try:
            with create_private_file(tmp) as fh:
                while chunk := await upload.read(CHUNK_SIZE):
                    total += len(chunk)
                    if total > max_bytes:
                        raise UploadTooLargeError(f"The file exceeds the maximum allowed size of {max_bytes} bytes.")
                    fh.write(chunk)
            if total == 0:
                raise EmptyUploadError()
        except BaseException:
            remove_file(tmp)
            raise
        return tmp, total
